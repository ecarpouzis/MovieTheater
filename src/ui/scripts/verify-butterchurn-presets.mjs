// Renders every butterchurn preset in a real browser and records which ones are broken.
//
// This is the gate behind scripts/butterchurn-denylist.json. The converted corpus is 1,754 presets
// scraped from the Milkdrop community, and a handful of them don't survive the conversion: the
// shader fails to compile, an equation throws, or the preset takes the WebGL context down with it.
// Those look like "the visualizer broke" to a user, so they get filtered out at publish time.
//
// It is deliberately CONSERVATIVE about what it condemns. A preset is denylisted only when it
// THROWS or kills the GL context — never for looking dark. Butterchurn is driven here by synthetic
// noise, not music, so "renders black" is a perfectly normal thing for a good preset to do; luma is
// recorded for information but is not a verdict.
//
// Chunked + resumable (a full pass is ~1,750 GPU preset loads): each run does a bounded batch,
// writes its verdicts to the results file, and prints what remains. Re-running continues where it
// stopped; nothing is re-checked.
//
//   node scripts/verify-butterchurn-presets.mjs --limit 200
//   node scripts/verify-butterchurn-presets.mjs --limit 200 --results <path>
//   node scripts/verify-butterchurn-presets.mjs --write-denylist     # emit the committed denylist
//
// Not wired into any npm hook — it needs Playwright + a GPU-ish browser, and its OUTPUT (the
// denylist) is what the build consumes.

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgDir = join(here, "..", "node_modules", "butterchurn-presets");
const srcDir = join(pkgDir, "presets", "converted");
const butterchurnLib = join(here, "..", "node_modules", "butterchurn", "lib", "butterchurn.min.js");
const denylistPath = join(here, "butterchurn-denylist.json");

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const at = args.indexOf(name);
  return at >= 0 && args[at + 1] ? args[at + 1] : fallback;
};
const LIMIT = Number(flag("--limit", "150"));
const RESULTS = resolve(flag("--results", join(here, "..", "..", "..", "scratchpad", "butterchurn-verify.json")));
const WRITE_DENYLIST = args.includes("--write-denylist");

const FRAMES = 12;      // enough to compile the shaders, run init + per-frame + per-pixel, and blend in
const PRESET_MS = 20000; // per-preset budget before the run is abandoned
const MAX_TRIES = 3;     // ⚠ a timeout is RETRIED, never a verdict — see below

// A timeout says "this machine was busy", not "this preset is broken". The first full sweep proved
// it: `Unchained - All You Can Eat` timed out under load and, re-checked alone, loaded in 5 ms and
// rendered at 1–6 ms/frame. Condemning on a timeout would have silently deleted a good preset — so
// timeouts accumulate a try count instead, and only a preset that times out MAX_TRIES times in a
// row is treated as genuinely wedged. Everything else (a throw, a lost context) is a verdict at once.
const isRetryable = (verdict) => !verdict.ok && verdict.err === "timeout" && (verdict.tries ?? 1) < MAX_TRIES;

function loadResults() {
  if (!existsSync(RESULTS)) return {};
  try {
    return JSON.parse(readFileSync(RESULTS, "utf8"));
  } catch {
    console.warn(`[verify] ${RESULTS} is unreadable — starting a fresh results file.`);
    return {};
  }
}

function saveResults(results) {
  mkdirSync(dirname(RESULTS), { recursive: true });
  writeFileSync(RESULTS, JSON.stringify(results, null, 1));
}

const names = readdirSync(srcDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.slice(0, -".json".length))
  .sort();

if (WRITE_DENYLIST) {
  const results = loadResults();
  const checked = names.filter((n) => results[n]);
  const unresolved = checked.filter((n) => isRetryable(results[n]));
  const broken = checked.filter((n) => !results[n].ok && !isRetryable(results[n])).sort();
  if (unresolved.length) {
    console.warn(
      `[verify] ${unresolved.length} preset(s) still have a retryable timeout and are NOT in the ` +
        `denylist. Re-run the verifier to settle them.`
    );
  }
  const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
  // `manual` is hand-maintained and must SURVIVE a regeneration — it carries judgement calls this
  // script is deliberately unable to make (see the denylist file's own comment).
  const existingManual = existsSync(denylistPath)
    ? JSON.parse(readFileSync(denylistPath, "utf8")).manual ?? []
    : [];
  writeFileSync(
    denylistPath,
    `${JSON.stringify(
      {
        _comment:
          "`broken` is GENERATED by scripts/verify-butterchurn-presets.mjs — presets that threw or " +
          "killed the WebGL context. `manual` is HAND-MAINTAINED and preserved across regeneration. " +
          "Both are subtracted by scripts/build-butterchurn-presets.mjs. Re-run the verifier if " +
          "butterchurn-presets is upgraded.",
        source: `butterchurn-presets@${version}`,
        checked: checked.length,
        broken,
        manual: existingManual,
      },
      null,
      2
    )}\n`
  );
  console.log(`[verify] wrote ${denylistPath}: ${broken.length} broken of ${checked.length} checked.`);
  process.exit(0);
}

const results = loadResults();
const todo = names.filter((n) => !results[n] || isRetryable(results[n])).slice(0, LIMIT);
if (todo.length === 0) {
  console.log(`[verify] nothing to do — all ${names.length} presets already checked. ` +
    `Run with --write-denylist to emit the denylist.`);
  process.exit(0);
}

// Playwright is not a dependency of the UI (this script is a tool, not part of the build). Take it
// from wherever it already lives: a local install, or an explicit path/`PLAYWRIGHT_MODULE` — e.g.
// the npx cache that `npx playwright` uses.
async function importPlaywright() {
  const explicit = flag("--playwright", process.env.PLAYWRIGHT_MODULE);
  for (const spec of [explicit, "playwright"].filter(Boolean)) {
    try {
      const mod = await import(spec.startsWith(".") || spec.includes(":") || spec.startsWith("/")
        ? new URL(`file://${resolve(spec).replace(/\\/g, "/")}/index.js`).href
        : spec);
      // Playwright is CJS: loaded through import() its exports land on .default, not as named ones.
      if (mod?.chromium) return mod;
      if (mod?.default?.chromium) return mod.default;
    } catch { /* try the next candidate */ }
  }
  throw new Error(
    "playwright not found. Install it here, or pass --playwright <path to the playwright module> " +
      "(PLAYWRIGHT_MODULE also works)."
  );
}

const { chromium } = await importPlaywright();
const browser = await chromium.launch({
  args: [
    "--autoplay-policy=no-user-gesture-required",
    // SwiftShader is fine here: this checks whether shaders COMPILE and equations RUN, which is a
    // correctness question. It says nothing about frame rate, and this script never claims to.
    "--use-gl=angle",
    "--use-angle=swiftshader",
    "--enable-unsafe-swiftshader",
  ],
});
const page = await browser.newPage();
await page.goto("about:blank");

const consoleErrors = [];
page.on("console", (msg) => {
  if (msg.type() === "error") consoleErrors.push(msg.text().slice(0, 300));
});
page.on("pageerror", (err) => consoleErrors.push(`pageerror: ${String(err).slice(0, 300)}`));

// One visualizer for the whole batch; rebuilt only if a preset takes the GL context down. Kept as
// a source string because a reload wipes the page's globals — it has to be re-evaluated, not just
// re-called.
const SETUP = () => {
  const canvas = document.createElement("canvas");
  canvas.width = 640;
  canvas.height = 360;
  document.body.innerHTML = "";
  document.body.appendChild(canvas);
  const ctx = new (window.AudioContext || window.webkitAudioContext)();
  ctx.resume?.();
  // White noise so the audio-reactive equations get real, varying input instead of a flat zero
  // vector (several presets divide by the audio levels).
  const buf = ctx.createBuffer(2, ctx.sampleRate, ctx.sampleRate);
  for (let c = 0; c < 2; c += 1) {
    const d = buf.getChannelData(c);
    for (let i = 0; i < d.length; i += 1) d[i] = Math.random() * 2 - 1;
  }
  const src = ctx.createBufferSource();
  src.buffer = buf;
  src.loop = true;
  const gain = ctx.createGain();
  gain.gain.value = 0.0001;
  src.connect(gain);
  src.start();
  const butterchurn = window.butterchurn.default ?? window.butterchurn;
  const viz = butterchurn.createVisualizer(ctx, canvas, {
    width: 640,
    height: 360,
    pixelRatio: 1,
    textureRatio: 1,
  });
  viz.connectAudio(gain);
  window.__viz = viz;
  window.__gl = canvas.getContext("webgl2");
};

async function rebuildPage() {
  await page.addScriptTag({ path: butterchurnLib });
  await page.evaluate(SETUP);
}

await rebuildPage();

async function checkPreset(preset, frames) {
  return page.evaluate(
    async ({ preset, frames }) => {
      const viz = window.__viz;
      const gl = window.__gl;
      try {
        viz.loadPreset(preset, 0);
        for (let i = 0; i < frames; i += 1) {
          viz.render();
          // Yield so the GL commands flush and a context loss becomes observable.
          // ⚠ setTimeout, NOT requestAnimationFrame. rAF is paced by the compositor, and a headless
          // page's compositor is not a clock you can rely on — under load it stalled hard enough to
          // blow a 20 s budget on a preset that renders in 1-6 ms/frame, which the harness then
          // reported as a broken preset. Nothing here needs a real frame boundary: the luma read
          // below takes its own render() immediately before readPixels.
          await new Promise((r) => setTimeout(r, 0));
        }
      } catch (err) {
        return { ok: false, err: String(err && err.message ? err.message : err).slice(0, 300) };
      }
      if (gl.isContextLost()) return { ok: false, err: "webgl context lost" };
      // Informational only — see the header note about why darkness is not a verdict.
      // ⚠ The drawing buffer is cleared as soon as the compositor takes it, and butterchurn owns the
      // context so preserveDrawingBuffer can't be set. readPixels must therefore follow a render()
      // with NO rAF (i.e. no frame boundary) in between, or it reads an empty buffer every time.
      try {
        viz.render();
      } catch (err) {
        return { ok: false, err: String(err && err.message ? err.message : err).slice(0, 300) };
      }
      const px = new Uint8Array(640 * 360 * 4);
      gl.readPixels(0, 0, 640, 360, gl.RGBA, gl.UNSIGNED_BYTE, px);
      let sum = 0;
      let max = 0;
      for (let i = 0; i < px.length; i += 4 * 97) {
        const l = 0.299 * px[i] + 0.587 * px[i + 1] + 0.114 * px[i + 2];
        sum += l;
        if (l > max) max = l;
      }
      return { ok: true, luma: Math.round((sum / Math.ceil(px.length / (4 * 97))) * 10) / 10, max };
    },
    { preset, frames }
  );
}

let ok = 0;
let broken = 0;
for (const name of todo) {
  const preset = JSON.parse(readFileSync(join(srcDir, `${name}.json`), "utf8"));
  consoleErrors.length = 0;
  let verdict;
  try {
    verdict = await Promise.race([
      checkPreset(preset, FRAMES),
      new Promise((r) => setTimeout(() => r({ ok: false, err: "timeout" }), PRESET_MS)),
    ]);
  } catch (err) {
    verdict = { ok: false, err: `evaluate failed: ${String(err).slice(0, 200)}` };
  }
  if (!verdict.ok && consoleErrors.length) verdict.console = consoleErrors.slice(0, 2);
  if (verdict.err === "timeout") verdict.tries = (results[name]?.tries ?? 0) + 1;
  results[name] = verdict;
  // Flush often: a browser that dies mid-batch must not cost the whole batch's progress.
  if ((ok + broken) % 25 === 0) saveResults(results);
  if (verdict.ok) ok += 1;
  else {
    broken += 1;
    console.log(`  ✗ ${name} — ${verdict.err}${isRetryable(verdict) ? ` (try ${verdict.tries}/${MAX_TRIES}, will retry)` : ""}`);
    // A dead context poisons every later preset, so rebuild before moving on.
    const lost = await page.evaluate(() => !window.__gl || window.__gl.isContextLost());
    if (lost) {
      await page.reload();
      await rebuildPage();
    }
  }
}

saveResults(results);
await browser.close();

const done = names.filter((n) => results[n] && !isRetryable(results[n])).length;
console.log(
  `[verify] batch: ${ok} ok, ${broken} broken. ` +
    `progress ${done}/${names.length}, ${names.length - done} remaining. results → ${RESULTS}`
);
