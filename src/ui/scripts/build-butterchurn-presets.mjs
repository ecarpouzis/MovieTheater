// Publishes the FULL butterchurn preset corpus as individually-fetchable static JSON.
//
// Why this exists: `butterchurn-presets` ships six webpack UMD bundles, and the app used to
// `import("butterchurn-presets")` — which is the 100-preset *base* pack, 646 kB of JS, all-or-nothing.
// The same npm package also ships `presets/converted/`: 1,754 preset JSON files, byte-identical to
// what the bundles hand back (verified by comparing `getPresets()[name]` to the file). Serving those
// as static assets gets ~17x the presets for a ~5 kB fetch each, and drops the 646 kB chunk entirely.
//
// Output (public/butterchurn/, gitignored — regenerated from node_modules, never committed, exactly
// like public/libass/):
//   presets/<slug>.json  — one preset each, copied verbatim (the source files are already minified)
//   index.json           — { count, presets: [{ s: slug, n: name, t: tier }] }
//
// Runs from the prestart/prebuild npm hooks and is safe to run anytime. If the package isn't
// installed it warns and no-ops rather than failing the build; the visualizer then shows its own
// "couldn't load presets" message instead of a broken canvas.

import { mkdirSync, copyFileSync, readdirSync, readFileSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url)); // src/ui/scripts
const pkgDir = join(here, "..", "node_modules", "butterchurn-presets");
const srcDir = join(pkgDir, "presets", "converted");
const outDir = join(here, "..", "public", "butterchurn");
const presetDir = join(outDir, "presets");

if (!existsSync(srcDir)) {
  console.warn("[butterchurn-presets] package not installed — skipping (the visualizer will report no presets).");
  process.exit(0);
}

// ── Tiers ───────────────────────────────────────────────────────────────────
// Not every one of the 1,754 is a keeper, and a random pick out of the whole corpus lands on a dud
// often enough to be noticeable. The package's own bundles ARE the curation: the base pack is what
// butterchurnviz.com ships as its default, and Extra/Extra2/MD1 are the maintained follow-ons. So
// pack membership becomes the tier, and the visualizer's auto-cycle draws from the good tiers by
// default while the picker still offers everything.
//   0 = featured  (base pack — the author's own default 100)
//   1 = classic   (Extra / Extra2 / MD1 — vetted, just not in the default pack)
//   2 = archive   (the rest of the converted corpus)
const TIER_PACKS = [
  ["butterchurnPresets"],
  ["butterchurnPresetsExtra", "butterchurnPresetsExtra2", "butterchurnPresetsMD1"],
];

// Presets that must not ship. Two sources, both in butterchurn-denylist.json:
//   `broken` — GENERATED by rendering every preset in headless Chromium
//              (scripts/verify-butterchurn-presets.mjs). Re-run it if the package is upgraded.
//   `manual` — hand-entered judgement calls, each with a written reason.
const denylistFile = JSON.parse(readFileSync(join(here, "butterchurn-denylist.json"), "utf8"));
const DENYLIST = new Set([
  ...(denylistFile.broken ?? []),
  ...(denylistFile.manual ?? []).map((entry) => entry.name),
]);

const require = createRequire(import.meta.url);

function packNames(pack) {
  try {
    const mod = require(join(pkgDir, "lib", `${pack}.min.js`));
    const presets = typeof mod.getPresets === "function" ? mod.getPresets() : mod;
    return Object.keys(presets);
  } catch (err) {
    console.warn(`[butterchurn-presets] could not read pack ${pack}: ${err.message}`);
    return [];
  }
}

const tierOf = new Map();
TIER_PACKS.forEach((packs, tier) => {
  for (const pack of packs) {
    for (const name of packNames(pack)) {
      if (!tierOf.has(name)) tierOf.set(name, tier);
    }
  }
});

// ── Slugs ───────────────────────────────────────────────────────────────────
// Preset names are Winamp-era filenames: "$$$ Royal - Mashup (197)", "!!!---flexi + amandio c - …",
// commas, brackets, quotes. Those survive a URL only through layers of escaping that a proxy or a
// static file server is free to normalise differently, so the wire name is a slug and the display
// name lives in the index.
function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90) || "preset";
}

const files = readdirSync(srcDir).filter((f) => f.endsWith(".json")).sort();

rmSync(presetDir, { recursive: true, force: true });
mkdirSync(presetDir, { recursive: true });

// ⚠ Every assigned slug, not a per-base counter. A counter is not enough: "_Geiss - Confetti
// (Kaleidoscope Mix)" collides with "Geiss - Confetti (Kaleidoscope Mix)" and is handed the
// suffixed "…-mix-2", which is ALSO the natural slug of "_Geiss - Confetti (Kaleidoscope Mix) 2".
// That silently overwrote one preset and left two index entries pointing at one file.
const used = new Set();
const entries = [];
let skipped = 0;
let denied = 0;

for (const file of files) {
  const name = file.slice(0, -".json".length);
  if (DENYLIST.has(name)) {
    denied += 1;
    continue;
  }

  // Parse to validate, but COPY the original bytes: the source files are already minified, and
  // re-serialising would only risk changing them.
  let preset;
  try {
    preset = JSON.parse(readFileSync(join(srcDir, file), "utf8"));
  } catch {
    skipped += 1;
    continue;
  }
  // The shape butterchurn's loadPreset needs. A file missing these would fail at shader-compile
  // time inside the render loop, where it reads as "the visualizer broke".
  // ⚠ Test for PRESENCE, not truthiness: `warp` and `comp` are empty strings on every Milkdrop-1-era
  // preset (no custom shader — butterchurn substitutes its default), and `pixel_eqs_str` is empty on
  // any preset with no per-pixel equations. A truthiness check here threw away 693 good presets,
  // including 18 from the base pack.
  if (
    !preset ||
    !preset.baseVals ||
    typeof preset.pixel_eqs_str !== "string" ||
    typeof preset.warp !== "string" ||
    typeof preset.comp !== "string"
  ) {
    skipped += 1;
    continue;
  }

  const base = slugify(name);
  let slug = base;
  for (let n = 2; used.has(slug); n += 1) slug = `${base}-${n}`;
  used.add(slug);

  copyFileSync(join(srcDir, file), join(presetDir, `${slug}.json`));
  entries.push({ s: slug, n: name, t: tierOf.get(name) ?? 2 });
}

// A duplicate slug means one preset overwrote another on disk and two index rows now point at the
// same file — silent data loss that only shows up as "that preset looks wrong". Fail loudly.
if (used.size !== entries.length) {
  console.error(`[butterchurn-presets] slug collision: ${entries.length} presets but ${used.size} unique slugs.`);
  process.exit(1);
}

const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
writeFileSync(
  join(outDir, "index.json"),
  JSON.stringify({ source: `butterchurn-presets@${version}`, count: entries.length, presets: entries })
);

const byTier = [0, 1, 2].map((t) => entries.filter((e) => e.t === t).length);
console.log(
  `[butterchurn-presets] published ${entries.length} presets ` +
    `(${byTier[0]} featured, ${byTier[1]} classic, ${byTier[2]} archive)` +
    `${denied ? `, ${denied} denylisted` : ""}${skipped ? `, ${skipped} malformed` : ""}`
);
